export function localizeEntry(entry: Entry, locale: Locale): Entry {
  const data = { ...entry.data };
  for (const key of Object.keys(data)) {
    if (!localizedKeys.has(key)) continue;
    const override = data[`${key}_${locale}`];
    if (override !== undefined && override !== "") data[key] = override;
    else {
      const translate = (v: string) =>
        locale === "en" ? terms[v] || v : spanish[v] || v;
      data[key] = Array.isArray(data[key])
        ? (data[key] as string[]).map(translate)
        : typeof data[key] === "string"
          ? translate(String(data[key]))
          : data[key];
    }
  }
  return { ...entry, data };
}
export function localizeContent(content: Content, locale: Locale): Content {
  const result = Object.fromEntries(
    collections.map((table) => [
      table,
      content[table].map((e) => localizeEntry(e, locale)),
    ]),
  ) as Content;
  // Translate category labels without breaking the canonical skill association.
  for (let i = 0; i < content.skills.length; i++) {
    const original = content.skills[i];
    const category = content.skill_categories.find(
      (c) => c.data.name === original.data.category,
    );
    if (category)
      result.skills[i].data.category = result.skill_categories.find(
        (c) => c.id === category.id,
      )!.data.name;
  }
  return result;
}
